import csv
import os
import platform
import statistics

import numpy as np

FIELDS = ["backend", "m", "k", "run", "seed", "pop_size", "max_gen", "error", "nfe", "seconds"]
START = "<!-- PERFORMANCE:START -->"
END = "<!-- PERFORMANCE:END -->"
NAME = {"numpy": "NumPy", "cupy": "CuPy"}


def load_rows(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def append_row(path, row):
    folder = os.path.dirname(path)
    if folder:
        os.makedirs(folder, exist_ok=True)
    first = not os.path.exists(path) or os.path.getsize(path) == 0
    with open(path, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        if first:
            w.writeheader()
        w.writerow(row)


def machine_info(backends):
    info = ["Python " + platform.python_version(), "NumPy " + np.__version__]

    cpu = platform.processor() or platform.machine()
    if os.path.exists("/proc/cpuinfo"):
        with open("/proc/cpuinfo") as f:
            for line in f:
                if line.startswith("model name"):
                    cpu = line.split(":", 1)[1].strip()
                    break
    info.append("CPU: " + cpu)

    if "cupy" in backends:
        import cupy as cp
        gpu = cp.cuda.runtime.getDeviceProperties(0)["name"]
        if isinstance(gpu, bytes):
            gpu = gpu.decode()
        info.append("CuPy " + cp.__version__)
        info.append("GPU: " + gpu)
    return info


def make_table(rows, pop_size, max_gen, info):
    rows = [r for r in rows if int(r["pop_size"]) == pop_size and int(r["max_gen"]) == max_gen]
    backends = [b for b in ("numpy", "cupy") if any(r["backend"] == b for r in rows)]

    cell = {}
    for r in rows:
        cell.setdefault((int(r["m"]), int(r["k"]), r["backend"]), []).append(r)
    mk = sorted(set((m, k) for m, k, _ in cell))

    head = ["m", "k", "len"]
    for b in backends:
        head += [NAME[b] + " error (mean ± std)", NAME[b] + " time / run (s)"]
    if len(backends) == 2:
        head.append("Speedup (NumPy / CuPy)")

    lines = ["| " + " | ".join(head) + " |", "|" + "---:|" * len(head)]
    for m, k in mk:
        line = [str(m), str(k), str(m * k)]
        t = {}
        for b in backends:
            rs = cell.get((m, k, b), [])
            if not rs:
                line += ["-", "-"]
                continue
            err = [float(r["error"]) for r in rs]
            sd = statistics.pstdev(err) if len(err) > 1 else 0.0
            t[b] = statistics.mean(float(r["seconds"]) for r in rs)
            line.append("%.3e ± %.1e (n=%d)" % (statistics.mean(err), sd, len(rs)))
            line.append("%.2f" % t[b])
        if len(backends) == 2:
            line.append("%.2fx" % (t["numpy"] / t["cupy"]) if len(t) == 2 else "-")
        lines.append("| " + " | ".join(line) + " |")

    text = ("`pop_size=%d`, `max_gen=%d` (NFE = %d per run). Error is the best fitness at the "
            "end of a run (global optimum = 0). Generated by `benchmark.py`."
            % (pop_size, max_gen, pop_size * max_gen))
    out = [text, ""]
    if info:
        out += ["Environment: " + "; ".join(info), ""]
    return "\n".join(out + lines)


def update_readme(path, table):
    text = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            text = f.read()

    block = START + "\n" + table + "\n" + END
    if START in text and END in text:
        before, rest = text.split(START, 1)
        after = rest.split(END, 1)[1]
        text = before + block + after
    else:
        text = text.rstrip() + "\n\n## Performance\n\n" + block + "\n"

    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
